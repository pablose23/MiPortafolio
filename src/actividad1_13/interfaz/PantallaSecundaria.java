    private void jButtonAltaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonAltaActionPerformed
        String nombre=jTextFieldNombre.getText();
        String apellido1=jTextFieldApellido1.getText();
        String apellido2=jTextFieldApellido2.getText();
        String curso=(String)jComboBoxCurso.getSelectedItem();
        ButtonModel selectedModel = buttonGroup1.getSelection();
        String turno=null;
        if(selectedModel!=null){
            turno=selectedModel.getActionCommand();
        }
        int nota=(int)jSpinnerNota.getValue();
        Clase clase= new Clase(nombre, apellido1, apellido2, curso, turno, nota);
        pantallaPrincipal.insertarClase(clase);
        dispose();
    }//GEN-LAST:event_jButtonAltaActionPerformed

