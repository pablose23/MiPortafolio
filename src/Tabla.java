    private void cargarEstudiantes() {
        btnCargar.setEnabled(false);
        btnCargar.setText("Cargando...");

        SwingWorker<List<Estudiante>, Void> worker = new SwingWorker<List<Estudiante>, Void>() {

            @Override
            protected List<Estudiante> doInBackground() throws Exception {
                return cargarEstudiantesDesdeBD();
            }

            @Override
            protected void done() {
                try {
                    List<Estudiante> estudiantes = get();
                    modelo.setEstudiantes(estudiantes);

                    JOptionPane.showMessageDialog(Tabla.this,
                            "Se cargaron " + estudiantes.size() + " estudiantes correctamente",
                            "Carga exitosa",
                            JOptionPane.INFORMATION_MESSAGE);

                } catch (Exception ex) {
                    logger.log(java.util.logging.Level.SEVERE, "Error al cargar estudiantes", ex);
                    JOptionPane.showMessageDialog(Tabla.this,
                            "Error al cargar estudiantes: " + ex.getMessage(),
                            "Error",
                            JOptionPane.ERROR_MESSAGE);
                }
            }
        };
        worker.execute();
    }
    
    private List<Estudiante> cargarEstudiantesDesdeBD() throws SQLException {
        List<Estudiante> estudiantes = new ArrayList<>();
        
        String sql = "SELECT id, nombre, apellidos, curiosidad, progreso FROM estudiantes";
        
        try (Connection conn = ConexionBD.getConnection();
             Statement stmt = conn.createStatement();
             ResultSet rs = stmt.executeQuery(sql)) {
            
            while (rs.next()) {
                Estudiante e = new Estudiante(
                    rs.getInt("id"),
                    rs.getString("nombre"),
                    rs.getString("apellidos"),
                    rs.getString("curiosidad"),
                    rs.getDouble("progreso")
                );
                estudiantes.add(e);
            }
        }
        
        return estudiantes;
    }
    
        private void mostrarCuriosidad() {
        int filaSeleccionada = jTable1.getSelectedRow();
        
        if (filaSeleccionada == -1) {
            JOptionPane.showMessageDialog(this, 
                "Por favor, selecciona un estudiante de la tabla",
                "Ninguna fila seleccionada",
                JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        Estudiante estudiante = modelo.getEstudianteAt(filaSeleccionada);
        
        if (estudiante != null) {
            jLabel3.setText(estudiante.getCuriosidad());
        }
    }
