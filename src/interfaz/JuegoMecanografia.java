    private void iniciarPartida() {
        contador = 1;
        puntos = 0;
        jButton1.setText("Reiniciar partida");
        tiempoInicio=System.currentTimeMillis();
        letraAleatoria();
        jLabel1.requestFocusInWindow();
    }

    private void reiniciarPartida() {
        contador = 0;
        puntos = 0;
        jLabel1.setText("");
        jButton1.setText("Iniciar partida");
    }

    private void letraSiguiente() {
        if (contador < 10) {
            letraAleatoria();
            contador++;
            this.requestFocusInWindow();
        } else {
            jLabel1.setText("");
            long tiempoFinal=System.currentTimeMillis();
            double tiempoSegundos=(tiempoFinal-tiempoInicio)/1000.0;
            JOptionPane.showMessageDialog(this, "¡Juego terminado!\nPuntos: " + puntos +
                "\nTiempo: " + String.format("%.2f", tiempoSegundos) + " segundos",
                "Resultado",
                JOptionPane.INFORMATION_MESSAGE);
            contador = 10;
        }
    }

    private void letraAleatoria() {
        letraActual = (char) ('a' + random.nextInt(26));
        jLabel1.setText(String.valueOf(letraActual));
    }

