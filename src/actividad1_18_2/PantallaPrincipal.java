    public void validar(){
        if(jTextField1.getText().isEmpty()){
            jLabel5.setText("*campo requerido");
        }else{
            jLabel5.setText("");
        }
        if(jTextField2.getText().isEmpty()){
            jLabel6.setText("*campo requerido");
        }else if(!jTextField2.getText().contains("@")||!jTextField2.getText().contains(".")){
            jLabel6.setText("*Correo invalido");
            jButton1.setEnabled(false);
        }
        if(jPasswordField1.getText().isEmpty()){
            jLabel7.setText("*campo requerido");
        }else{
            jLabel7.setText("");
        }
        if(jTextField1.getText().isEmpty()||jTextField2.getText().isEmpty()||jPasswordField1.getText().isEmpty()){
            jButton1.setEnabled(false);
        }else{
            jButton1.setEnabled(true);
        }
    }
