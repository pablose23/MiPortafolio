    private void jButtonConfirmacionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonConfirmacionActionPerformed
        int opcion
                = JOptionPane.showConfirmDialog(this, "¿Confirmamos?", "Confirmación", JOptionPane.YES_NO_OPTION);
        if (opcion == JOptionPane.YES_OPTION) {
            JOptionPane.showMessageDialog(this, "Pues confirmamos!", "Confirmacion de si", JOptionPane.INFORMATION_MESSAGE);
        } else if (opcion == JOptionPane.NO_OPTION) {
            JOptionPane.showMessageDialog(this, "Pues no confirmamos", "Confirmacion de no", JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_jButtonConfirmacionActionPerformed

