    private void jComboBox1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jComboBox1ActionPerformed
        String animales = (String) jComboBox1.getSelectedItem();
        switch (animales) {
            case "Caballo":
                Icon icono= new ImageIcon(new ImageIcon(getClass().getResource("imgs/caballo.jpeg")).getImage());
                jLabelCBox.setIcon(icono);
                break;
            case "Perro":
                Icon icono2= new ImageIcon(new ImageIcon(getClass().getResource("imgs/perro.jpeg")).getImage());
                jLabelCBox.setIcon(icono2);
                break;
            case "Gato":
                Icon icono3= new ImageIcon(new ImageIcon(getClass().getResource("imgs/gato.jpeg")).getImage());
                jLabelCBox.setIcon(icono3);
                break;
        }
    }//GEN-LAST:event_jComboBox1ActionPerformed

